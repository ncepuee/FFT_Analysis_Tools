function splashFile = createFFTAnalysisSplash(outputFolder)
%CREATEFFTANALYSISSPLASH Create the splash image used by the compiled app.

    if nargin < 1 || strlength(string(outputFolder)) == 0
        outputFolder = fullfile(fileparts(mfilename('fullpath')), 'resources');
    end

    if ~isfolder(outputFolder)
        mkdir(outputFolder);
    end

    splashFile = fullfile(outputFolder, 'FFTAnalysisSplash.png');

    fig = figure('Visible', 'off', ...
        'Units', 'pixels', ...
        'Position', [100 100 800 800], ...
        'Color', [0.055 0.07 0.085], ...
        'InvertHardcopy', 'off', ...
        'MenuBar', 'none', ...
        'ToolBar', 'none');
    cleanup = onCleanup(@() close(fig));

    ax = axes(fig, 'Position', [0 0 1 1]);
    axis(ax, 'off');
    hold(ax, 'on');
    xlim(ax, [0 1]);
    ylim(ax, [0 1]);

    rectangle(ax, 'Position', [0 0 1 1], ...
        'FaceColor', [0.055 0.07 0.085], ...
        'EdgeColor', 'none');
    rectangle(ax, 'Position', [0 0 1 0.34], ...
        'FaceColor', [0.025 0.035 0.043], ...
        'EdgeColor', 'none');

    t = linspace(0.07, 0.93, 900);
    y = 0.35 + 0.055 * sin(2*pi*7*t) + 0.018 * sin(2*pi*31*t);
    plot(ax, t, y, 'Color', [0.1 0.58 0.95], 'LineWidth', 2.2);
    plot(ax, t, y + 0.105, 'Color', [0.95 0.54 0.16], 'LineWidth', 1.4);

    freqX = linspace(0.12, 0.88, 36);
    amp = 0.035 + 0.18 * exp(-((freqX - 0.36) / 0.08).^2) + ...
        0.09 * exp(-((freqX - 0.64) / 0.12).^2);
    for k = 1:numel(freqX)
        plot(ax, [freqX(k), freqX(k)], [0.11, 0.11 + amp(k)], ...
            'Color', [0.65 0.78 0.86], ...
            'LineWidth', 2.5);
    end

    text(ax, 0.07, 0.82, 'FFT Analysis Tools', ...
        'Color', [0.96 0.98 1.00], ...
        'FontName', 'Arial', ...
        'FontWeight', 'bold', ...
        'FontSize', 42);
    text(ax, 0.073, 0.755, 'MATLAB FFT / THD analysis', ...
        'Color', [0.72 0.82 0.90], ...
        'FontName', 'Arial', ...
        'FontSize', 18);
    text(ax, 0.073, 0.708, 'MAT and oscilloscope CSV data', ...
        'Color', [0.72 0.82 0.90], ...
        'FontName', 'Arial', ...
        'FontSize', 16);
    text(ax, 0.07, 0.63, 'Copyright (c) 2026 Zhenbin Huang', ...
        'Color', [0.95 0.69 0.34], ...
        'FontName', 'Arial', ...
        'FontSize', 17, ...
        'FontWeight', 'bold');
    text(ax, 0.07, 0.575, 'ORCID: https://orcid.org/0000-0002-0628-0387', ...
        'Color', [0.82 0.88 0.92], ...
        'FontName', 'Arial', ...
        'FontSize', 11);
    text(ax, 0.07, 0.535, 'LinkedIn: linkedin.com/in/zhenbin-huang', ...
        'Color', [0.82 0.88 0.92], ...
        'FontName', 'Arial', ...
        'FontSize', 11);

    print(fig, splashFile, '-dpng', '-r120');
end
